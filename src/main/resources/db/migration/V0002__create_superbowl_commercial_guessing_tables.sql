CREATE TABLE sb_commercial_game (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'CLOSED',
    winning_category VARCHAR(255),
    guessing_opens_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE sb_commercial_guess (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES sb_commercial_game(id),
    guesser_name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    guessed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);
